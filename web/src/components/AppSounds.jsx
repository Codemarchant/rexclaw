import React, { useMemo, useState } from "react";
import { _t } from "../lib/i18n";

/** History → Recordings → App sounds: every recorded sound that ships with
 *  the app (server/routes/audio.py _app_sounds), grouped by what it is for,
 *  each with its description and a player. Read-only: the user's own sounds
 *  live under Your sounds. */

// [group key, title, how it is used (%s = the sound's name), what the group is]
const GROUPS = [
    ["effects", "Call sound effects", "%s",
     "The soundboard companions play on voice calls (Sound effects, switched on per companion). Each avatar chooses which of these it gets in the avatar editor's Sound effects section. To replace one, add a call sound effect with the same name under Your sounds."],
    ["beds", "Recording beds", "{bed %s}",
     "Looping backgrounds for scripts and voice messages."],
    ["music", "Recording music", "{music %s}",
     "Looping music for scripts and voice messages, which also sits in the music library companions play background music from in calls."],
    ["avatar_music", "Companion background music", "%s",
     "The background music the built-in avatars bring to calls."],
];

export function countAppSounds(appSounds) {
    return GROUPS.reduce((n, [key]) => n + (appSounds?.[key]?.length || 0), 0);
}

export default function AppSounds({ appSounds }) {
    const [query, setQuery] = useState("");
    const groups = useMemo(() => {
        const q = query.trim().toLowerCase();
        return GROUPS.map(([key, title, use, about]) => {
            const all = appSounds?.[key] || [];
            const sounds = q ? all.filter((s) => [s.name, s.description, s.credit, s.avatar].join("\n")
                .toLowerCase().includes(q)) : all;
            return { key, title, use, about, sounds, total: all.length };
        }).filter((g) => g.total);
    }, [appSounds, query]);

    return (
        <>
            <p className="text-muted small" style={{ margin: "0.4rem 0 0.2rem" }}>
                {_t("The sounds that come with the app. They can't be edited or deleted; add your own under Your sounds. The ocean, rain, noise and drone beds and the chime are generated by the studio as it renders, so they have no file to play here.")}
            </p>
            <div className="rx_mem_toolbar">
                <input type="text" value={query} placeholder={_t("Search names, descriptions, credits…")}
                       onChange={(ev) => setQuery(ev.target.value)} />
            </div>
            {groups.map((g) => (
                // Open while searching, so matches show without a click.
                <details key={g.key} open={query.trim() ? g.sounds.length > 0 : undefined}
                         style={{ margin: "0.3rem 0" }}>
                    <summary style={{ cursor: "pointer" }} title={_t(g.about)}>
                        <strong>{_t(g.title)}</strong>{" "}
                        <span className="text-muted small">
                            {g.sounds.length < g.total ? _t("%s of %s sounds", g.sounds.length, g.total) : g.total}
                        </span>
                    </summary>
                    <p className="text-muted small" style={{ margin: "0.2rem 0" }}>{_t(g.about)}</p>
                    {g.sounds.map((s) => (
                        <div key={s.url} className="rx_studio_rec">
                            <div className="rx_studio_rec_head">
                                <code>{g.use.replace("%s", s.name)}</code>
                                {s.avatar && <span className="rx_studio_badge">{s.avatar}</span>}
                                {s.replaced && (
                                    <span className="rx_studio_badge"
                                          title={_t("A call sound effect of yours has this name, so companions play yours instead.")}>
                                        {_t("Replaced by yours")}
                                    </span>
                                )}
                            </div>
                            {(s.description || s.credit) && (
                                <div className="text-muted small" style={{ marginTop: "0.2rem" }}>
                                    {s.description}{s.description && s.credit ? " · " : ""}{s.credit && <em>{s.credit}</em>}
                                </div>
                            )}
                            <audio src={s.url} controls preload="none" />
                        </div>
                    ))}
                </details>
            ))}
        </>
    );
}
